from pydantic import BaseModel, Field
import time
from typing import Literal

db_processed_keys = set() # Mock database of processed keys

class RefundInput(BaseModel):
    user_id: int = Field(description="The ID of the user.")
    amount: float = Field(description="The refund amount.")
    idempotency_key: str = Field(description="A unique UUID v4 generated by the agent for this specific transaction attempt.")

class Approval(BaseModel):
    idempotency_key: str
    expires_at: float
    approver_role: Literal['agent', 'manager', 'admin']
    approved_action: str

def validate_approval(approval: Approval | None, expected_action: str):
    if not approval:
        raise ValueError("Missing approval")
    if time.time() > approval.expires_at:
        raise ValueError("Expired approval")
    if approval.approved_action != expected_action:
        raise ValueError("Approval for different action")
    if approval.approver_role not in ['manager', 'admin']:
        raise ValueError("Unauthorized approver")

def process_refund_safe(user_id: int, amount: float, idempotency_key: str, approval: Approval | None = None):
    validate_approval(approval, "refund")
    
    if idempotency_key in db_processed_keys:
        print(f"   [API] Ignoring duplicate request. Key {idempotency_key} already processed.")
        return "Refund already processed (Idempotent success)."
        
    print(f"   [API] Processing new refund of ${amount} for User {user_id}...")
    db_processed_keys.add(idempotency_key)
    return "Refund processed successfully."
